function build(seed: Seed): LegacyOffer {
  const validUntil = offsetDate(seed.until);
  const validFrom = offsetDate(seed.from ?? seed.created ?? -30);
  return {
    id: seed.slug,
    slug: seed.slug,
    brandId: seed.brandId,
    title: seed.title,
    shortDescription: seed.shortDescription,
    description: seed.description,
    discountLabel: seed.discountLabel,
    discountUnit: seed.discountUnit,
    savingScore: seed.savingScore,
    offerType: seed.offerType,
    category: seed.category,
    image: { pattern: seed.pattern, accent: seed.accent, tone: seed.tone ?? "light" },
    validFrom,
    validUntil,
    featured: seed.featured ?? false,
    recommended: seed.recommended ?? false,
    recommendationReason: seed.reason,
    eligibility: seed.eligibility,
    howToUse: seed.howToUse ?? HOW_TO_USE[seed.offerType],
    terms: [
      `Runs until ${formatDateLong(validUntil)} unless the brand withdraws it earlier.`,
      ...(seed.terms ?? []),
      TYPE_TERMS[seed.offerType],
      "Saving an offer to your Wallet does not reserve it or guarantee availability.",
    ],
    tags: seed.tags,
    status: seed.status ?? "live",
    createdAt: offsetDate(seed.created ?? -30),
    merchantId: `m_${seed.brandId}`,
  };
}

export const offers: LegacyOffer[] = seeds.map(build);
