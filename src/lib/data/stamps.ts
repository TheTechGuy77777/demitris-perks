export const stampCampaignById = Object.fromEntries(stampCampaigns.map((campaign) => [campaign.id, campaign])) as Record<string, StampCampaign>;

export function getStampCampaign(slug: string) {
  return stampCampaigns.find((campaign) => campaign.slug === slug);
}

export function stampStatusLabel(status: StampCampaign["status"]) {
  if (status === "ending-soon") return "Ending soon";
  if (status === "ended") return "Ended";
  return "Live";
}
